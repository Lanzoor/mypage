    <h1>About Past Tenses in English</h1>

    <p>So, past tenses. They exist. Let's talk about them.</p>

    <p>
        At first, they seem simple. Most sources introduce past tenses as forms
        used to describe events that happened in the past.
    </p>

    <p>
        That explanation is perfectly valid, yes, but there are... <i>some</i>
        cases that can melt the brain of a new learner. Here's an example:
    </p>

    <div class="example">
        <i>Could</i> you get me some water?
    </div>

    <p>
        You probably know that <b>could</b> is historically related to the past
        form of <b>can</b>. But in a sentence like this, could isn't referring
        to past time at all. In fact, it's a request being made...
        <i>right now</i>.
    </p>

    <p>
        And yet, using <i>could</i> here makes <b>perfect sense.</b> It even makes
        the request sound more polite or less direct. Let's keep going. Take a look
        at this sentence:
    </p>

    <div class="example">
        If I <i>had</i> known about this earlier, I <i>would</i> have been going places
        now.
    </div>

    <p>
        This sentence describes a hypothetical scenario. <b
            >It isn't even describing something that actually happened. So why
            in the actual world is a past tense being used here?</b
        >
    </p>

    <h2>What Past Tenses <i>Truly</i> Are</h2>

    <p>Well, let's stop yapping and jump to the conclusion.</p>

    <p>
        <b>
            Past tenses don't just describe the past. They can also indicate
            <i>distance</i>.
        </b>
        Some sort of distance. Remember that word, because it will be important.
    </p>

    <p>So, what does this actually mean? Let's look at a few examples.</p>

    <h3>Temporal Distance</h3>

    <p>
        This is the use of past tense that you already know and love. It
        indicates <i>temporal distance</i>, or distance in time. Look at this
        sentence:
    </p>

    <div class="example">
        I <i>ate</i> a hamburger.
    </div>

    <p>
        There are two points in time involved here. First, there is the event of
        me eating a hamburger. Then, there is the moment when I describe that
        event. The eating happened <i>before</i> the description, so the past tense
        places the event at a temporal distance from the moment of speaking.
    </p>

    <h3>Social Distance</h3>

    <p>Take a look at this sentence again:</p>

    <div class="example">
        <i>Could</i> you get me some water?
    </div>

    <p>
        This can, in many contexts, be exchanged for
        <b>"<i>Can</i> you get me some water?"</b>. So what's the difference?
    </p>

    <p>
        The version with <i>could</i> often feels more polite, indirect, or
        formal, while the version with <i>can</i> tends to feel more direct and
        casual. The "past" form isn't creating a distance in time here. Instead,
        it creates a kind of <i>social distance</i> between the speaker and the listener,
        making the request less direct and more polite and formal.
    </p>

    <h3>Psychological Distance</h3>

    <div class="example">
        I <i>wanted</i> to ask you something.<br />
        I <i>was</i> wondering if I <i>could</i> ask you something.
    </div>

    <p>
        The speaker is not saying that they literally wanted to ask the listener
        something but no longer need it. Nope. Instead, the past form creates
        some sort of psychological distance from the speaker's current
        intention, which makes the statement sound less abrupt and more gentle.
    </p>

    <h3>Hypothetical Distance</h3>

    <p>Remember the sentence from earlier?</p>

    <div class="example">
        If I <i>had</i> known about this earlier, I <i>would</i> have been going places
        now.
    </div>

    <p>
        Notice the <i>distance</i> between the reality the speaker is in and the hypothetical
        reality they are describing. The past forms help signal that the situation
        being described is removed from the speaker's current reality.
    </p>

    <p>Here are a few more examples:</p>

    <div class="example">
        If you <i>had</i> a million dollars, what <i>would</i> you buy first?<br
        />
        If you <i>could</i> only speak one language from now on, which language
        <i>would</i> you choose?
    </div>

    <p>
        Instead of trying to answer these questions, try to notice the patterns.
        In each case, there is some kind of <i>distance</i> between the speaker's
        current reality and the reality being described.
    </p>

    <h3>Narrative Distance</h3>

    <div class="example">
        Once upon a time, there <i>was</i> a beast named Lanzoor.
    </div>

    <p>
        The events don't necessarily have to be in the real past. The past tense
        can simply establish the story as something separate from the speaker's
        immediate reality. This is why past-tense narration is quite common in
        traditional storytelling.
    </p>

    <h2>Verdict</h2>

    <p>
        <b>English past forms aren't limited to talking about the past.</b> In many
        situation, they tend to express some kind of distance or remoteness, whether
        it's distance in time, social distance, psychological distance, or distance
        from reality.
    </p>

    <p>
        Unfortunately the examples above aren't everything. There are still
        plenty of exceptions. I mean, what else did you expect? It's <i
            >literally English.</i
        >
        You can't really expect much from it. But with the <i>distance</i> mental
        model, you should be able to spot these patterns a little more easily. Good
        luck.
    </p>
